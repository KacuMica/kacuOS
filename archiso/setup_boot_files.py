#!/usr/bin/env python3
# ==========================================================================
# setup_boot_files.py — populate an archiso profile with bootloader files.
#
# Copies syslinux/, efiboot/, grub/ and pacman.conf from the official releng
# reference profile. It does NOT overwrite an existing profiledef.sh unless
# --force-profiledef is given (the GNOME profile has a hand-maintained one).
#
# Usage:
#   ./setup_boot_files.py kacu-desktop
#   ./setup_boot_files.py kacu-server --force-profiledef
# ==========================================================================
from __future__ import annotations

import argparse
import shutil
import stat
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
RELENG = Path("/usr/share/archiso/configs/releng")

BOOT_PACKAGES = ["syslinux", "memtest86+", "edk2-shell", "mkinitcpio-archiso"]


def write_profiledef(profile_dir: Path, name: str) -> None:
    content = f"""#!/usr/bin/env bash
# Generated by setup_boot_files.py — edit if you need profile-specific tuning.
# shellcheck disable=SC2034
iso_name="{name}"
iso_label="KACUOS_$(date --date="@${{SOURCE_DATE_EPOCH:-$(date +%s)}}" +%Y%m)"
iso_publisher="kacuOS <https://github.com/kacu-os/kacuOS>"
iso_application="kacuOS Live/Install"
iso_version="$(date --date="@${{SOURCE_DATE_EPOCH:-$(date +%s)}}" +%Y.%m.%d)"
install_dir="arch"
buildmodes=('iso')
bootmodes=('bios.syslinux'
           'uefi.systemd-boot')
pacman_conf="pacman.conf"
airootfs_image_type="squashfs"
airootfs_image_tool_options=('-comp' 'xz' '-Xbcj' 'x86' '-b' '1M' '-Xdict-size' '1M')
bootstrap_tarball_compression=('zstd' '-c' '-T0' '--auto-threads=logical' '--long' '-19')
file_permissions=(
  ["/root/customize_airootfs.sh"]="0:0:755"
  ["/usr/local/bin/kacu-setup"]="0:0:755"
  ["/usr/local/bin/kacu-pkg"]="0:0:755"
  ["/usr/local/bin/kacu_install"]="0:0:755"
  ["/usr/local/bin/kacuctl"]="0:0:755"
  ["/usr/local/bin/kacu-sysinfo"]="0:0:755"
  ["/etc/kacu/presets/hooks/server-post.py"]="0:0:755"
  ["/etc/kacu/presets/hooks/ai-post.py"]="0:0:755"
)
"""
    path = profile_dir / "profiledef.sh"
    path.write_text(content, encoding="utf-8", newline="\n")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def ensure_packages(profile_dir: Path) -> None:
    package_file = profile_dir / "packages.x86_64"
    existing = set(package_file.read_text(encoding="utf-8").split())
    additions = [pkg for pkg in BOOT_PACKAGES if pkg not in existing]
    if additions:
        with package_file.open("a", encoding="utf-8", newline="\n") as fh:
            fh.write("\n# --- bootloader (added by setup_boot_files.py) ---\n")
            for pkg in additions:
                fh.write(f"{pkg}\n")
        print(f"  added to packages.x86_64: {', '.join(additions)}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Populate an archiso profile with boot files")
    parser.add_argument("profile", help="profile directory name, e.g. kacu-desktop")
    parser.add_argument("--force-profiledef", action="store_true",
                        help="overwrite an existing profiledef.sh")
    args = parser.parse_args()

    profile_dir = SCRIPT_DIR / args.profile
    if not profile_dir.is_dir():
        print(f"error: profile directory not found: {profile_dir}", file=sys.stderr)
        return 1
    if not RELENG.is_dir():
        print(f"error: releng reference profile not found at {RELENG}\n"
              "       install it with: sudo pacman -S archiso", file=sys.stderr)
        return 1

    print(f"==> copying bootloader files from {RELENG} into {profile_dir.name}")
    for name in ("syslinux", "efiboot", "grub"):
        src = RELENG / name
        dst = profile_dir / name
        if src.is_dir():
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(src, dst)
            print(f"  copied {name}/")
    pacman_conf = RELENG / "pacman.conf"
    if pacman_conf.is_file() and not (profile_dir / "pacman.conf").exists():
        shutil.copy2(pacman_conf, profile_dir / "pacman.conf")
        print("  copied pacman.conf")

    profiledef = profile_dir / "profiledef.sh"
    if args.force_profiledef or not profiledef.exists():
        write_profiledef(profile_dir, args.profile)
        print("  wrote profiledef.sh")
    else:
        print("  kept existing profiledef.sh (use --force-profiledef to replace)")

    # Live-boot mkinitcpio hooks (required for the ISO image).
    mkinitcpio_src = RELENG / "airootfs/etc/mkinitcpio.conf.d"
    if mkinitcpio_src.is_dir():
        dst = profile_dir / "airootfs/etc/mkinitcpio.conf.d"
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(mkinitcpio_src, dst)
        print("  copied mkinitcpio.conf.d/")

    ensure_packages(profile_dir)
    print(f"\n==> done. Build with: cd {profile_dir.name} && sudo mkarchiso -v -o out/ .")
    return 0


if __name__ == "__main__":
    sys.exit(main())
